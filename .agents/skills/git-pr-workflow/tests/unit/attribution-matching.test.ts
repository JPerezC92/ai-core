import { describe, expect, it } from "vitest";
import {
	FIXTURE_HEAD_SHA,
	loadApprovedPolicy,
	makeAttributionLine,
	makeCaseFoldedAttributionLine,
	makeCaseFoldedIdentityPolicy,
	makeChangedFile,
	makeChangedFiles,
	makeMultilineMatchingContents,
	makeOrdinaryIdentityMention,
	makeSnapshotWithArtifactContent,
	scanAttribution,
} from "#tests/support/attribution-fixtures.ts";

/** Every approved marker, written literally so a policy change is visible here. */
const APPROVED_MARKERS: readonly { readonly index: number; readonly text: string }[] = [
	{ index: 0, text: "Co-authored-by:" },
	{ index: 1, text: "Generated by" },
	{ index: 2, text: "Created by" },
	{ index: 3, text: "Written by" },
	{ index: 4, text: "Authored by" },
	{ index: 5, text: "Assisted by" },
];

/** Every approved identity with the identities its own marker line must report. */
const APPROVED_IDENTITIES: readonly {
	readonly index: number;
	readonly text: string;
	readonly reported: readonly string[];
}[] = [
	{ index: 0, text: "OpenAI", reported: ["OpenAI"] },
	{ index: 1, text: "ChatGPT", reported: ["ChatGPT"] },
	{ index: 2, text: "GPT-", reported: ["GPT-"] },
	{ index: 3, text: "GitHub Copilot", reported: ["GitHub Copilot", "Copilot"] },
	{ index: 4, text: "Copilot", reported: ["Copilot"] },
	{ index: 5, text: "Anthropic", reported: ["Anthropic"] },
	{ index: 6, text: "Claude", reported: ["Claude"] },
	{ index: 7, text: "Google AI", reported: ["Google AI"] },
	{ index: 8, text: "Gemini", reported: ["Gemini"] },
	{ index: 9, text: "Cursor", reported: ["Cursor"] },
	{ index: 10, text: "Windsurf", reported: ["Windsurf"] },
	{ index: 11, text: "Devin", reported: ["Devin"] },
	{ index: 12, text: "[bot]", reported: ["[bot]"] },
];

describe("attribution matching", () => {
	it("matches every approved marker and identity pair the same line carries", () => {
		const policy = loadApprovedPolicy();

		for (const marker of APPROVED_MARKERS) {
			for (const identity of APPROVED_IDENTITIES) {
				const line = makeAttributionLine(policy, marker.index, identity.index);
				const snapshot = makeSnapshotWithArtifactContent(
					"commit-message",
					line,
					makeChangedFiles(makeChangedFile()),
				);

				const result = scanAttribution(snapshot, policy);

				expect(result.matches).toEqual(
					identity.reported.map((reportedIdentity) => ({
						surface: "commit-message",
						source: FIXTURE_HEAD_SHA,
						path: null,
						line: 1,
						marker: marker.text,
						identity: reportedIdentity,
					})),
				);
			}
		}
	});

	it("does not match an ordinary identity mention without a marker", () => {
		const policy = loadApprovedPolicy();
		const snapshot = makeSnapshotWithArtifactContent(
			"pr-body",
			makeOrdinaryIdentityMention(policy),
			makeChangedFiles(makeChangedFile()),
		);

		expect(scanAttribution(snapshot, policy).matches).toEqual([]);
	});

	it("matches case-insensitively and reports the surface, source, path and line", () => {
		const policy = loadApprovedPolicy();
		const { artifactContent, fileContent } = makeMultilineMatchingContents(policy);
		const snapshot = makeSnapshotWithArtifactContent(
			"commit-message",
			artifactContent,
			makeChangedFiles(makeChangedFile("src/example.py", fileContent)),
		);

		const matches = scanAttribution(snapshot, policy).matches;

		expect(matches).toEqual([
			{
				surface: "commit-message",
				source: FIXTURE_HEAD_SHA,
				path: null,
				line: 3,
				marker: "Co-authored-by:",
				identity: "OpenAI",
			},
			{
				surface: "changed-file",
				source: null,
				path: "src/example.py",
				line: 2,
				marker: "Co-authored-by:",
				identity: "OpenAI",
			},
		]);
		expect(matches.every((match) => !("content" in match))).toBe(true);
	});

	it("does not fold case beyond Unicode lowercasing", () => {
		// Documented difference: matching lowercases instead of applying full case
		// folding, so an identity carrying `ß` does not match its `ss` expansion.
		const policy = makeCaseFoldedIdentityPolicy();
		const snapshot = makeSnapshotWithArtifactContent(
			"commit-message",
			makeCaseFoldedAttributionLine(policy),
			makeChangedFiles(makeChangedFile()),
		);

		expect(scanAttribution(snapshot, policy).matches).toEqual([]);
	});
});
